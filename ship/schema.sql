-- ============================================================
-- Allergens — EU Reg. 1169/2011 Annex II
--
-- For food sold at a distance, allergen information must reach the customer
-- BEFORE they buy. A takeaway website is distance selling.
--
-- `allergens_reviewed` defaults to FALSE deliberately. Until someone in the
-- kitchen confirms a dish, the site shows "spørg os" rather than a list: an
-- unchecked dish and a dish with no allergens must not look the same to a
-- person with an allergy. See lib/allergens.ts and tests/allergens.test.ts.
-- ============================================================
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergens TEXT[] DEFAULT '{}';
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergens_reviewed BOOLEAN DEFAULT FALSE;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergen_note TEXT;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergens_reviewed_at TIMESTAMPTZ;

-- Only the 14 declarable allergens may be stored. A typo would otherwise be
-- dropped at display time and read as "cleared".
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'menu_items_allergens_valid') THEN
    ALTER TABLE menu_items ADD CONSTRAINT menu_items_allergens_valid CHECK (
      allergens <@ ARRAY['gluten','krebsdyr','aeg','fisk','jordnoedder','soja','maelk',
                         'noedder','selleri','sennep','sesam','sulfitter','lupin','bloeddyr']::TEXT[]
    );
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS menu_items_allergens_idx ON menu_items USING GIN (allergens);

-- How far the declaration can be trusted:
--   confirmed — a human in the kitchen checked this dish
--   standard  — derived from the dish type (sashimi is fish, tempura is wheat
--               batter). Shown to customers with "standardopskrift" attached.
--   uncertain — not knowable from the menu. Shows "ring til os" and nothing else.
--
-- The middle tier exists because marking all 101 dishes "ask us" is technically
-- safe and practically useless: a warning on everything stops being read.
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS allergen_confidence TEXT DEFAULT 'uncertain';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'menu_items_allergen_confidence_valid') THEN
    ALTER TABLE menu_items ADD CONSTRAINT menu_items_allergen_confidence_valid
      CHECK (allergen_confidence IN ('confirmed','standard','uncertain'));
  END IF;
END $$;

-- ============================================================
-- Searchable phone number
--
-- Customers type "31 33 44 86", "+45 31334486", "3133 4486". Stored verbatim,
-- none of those match a search for "31334486" — so the 30-day history lookup by
-- phone silently returned nothing for most customers. A generated column
-- normalises once, at write time, and cannot drift from the raw value.
-- ============================================================
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_name = 'orders' AND column_name = 'phone_digits'
  ) THEN
    ALTER TABLE orders ADD COLUMN phone_digits TEXT
      GENERATED ALWAYS AS (regexp_replace(COALESCE(customer_phone, ''), '[^0-9]', '', 'g')) STORED;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS orders_phone_digits_idx ON orders(phone_digits);


-- ============================================================
-- Retention: 30 days
--
-- Two reasons, pointing the same way. The kitchen needs to look up a disputed
-- order from last week; nobody needs one from last year. And these rows are
-- names and phone numbers — under GDPR, keeping them longer than the purpose
-- requires is the violation, so a fixed window is the compliant answer as well
-- as the useful one.
-- ============================================================
-- ============================================================
-- System events — self-contained monitoring
--
-- Without this, a checkout failing at 19:00 on a Friday is invisible until a
-- customer phones to ask where their food is. A restaurant should not need a
-- second SaaS account to learn its own ordering page is broken.
--
-- Events, not logs: one row per thing worth a human knowing about. Surfaced at
-- /kitchen/selftest and purged on the same 30-day cycle as orders.
-- ============================================================
CREATE TABLE IF NOT EXISTS system_events (
  id          UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at  TIMESTAMPTZ DEFAULT NOW(),
  severity    TEXT NOT NULL DEFAULT 'error',
  source      TEXT NOT NULL,
  message     TEXT NOT NULL,
  detail      JSONB,
  CONSTRAINT system_events_severity_valid CHECK (severity IN ('info','warn','error'))
);

CREATE INDEX IF NOT EXISTS system_events_recent_idx   ON system_events(created_at DESC);
CREATE INDEX IF NOT EXISTS system_events_severity_idx ON system_events(severity, created_at DESC);

-- Error messages can carry fragments of a request, so staff-only by construction.
ALTER TABLE system_events ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- Outbound message queue
--
-- Everything the system needs to tell a human goes here first: a customer's
-- "din mad er klar", an owner alert that checkout is failing. Nothing sends
-- directly, because the Android phone acting as SMS gateway is not always
-- reachable — it sleeps, loses signal, gets left in a coat. A queue waits; a
-- direct send is simply lost.
-- ============================================================
CREATE TABLE IF NOT EXISTS outbound_messages (
  id           UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at   TIMESTAMPTZ DEFAULT NOW(),
  channel      TEXT NOT NULL DEFAULT 'sms',
  recipient    TEXT NOT NULL,
  body         TEXT NOT NULL,
  status       TEXT NOT NULL DEFAULT 'pending',
  attempts     INT  NOT NULL DEFAULT 0,
  last_error   TEXT,
  sent_at      TIMESTAMPTZ,
  claimed_at   TIMESTAMPTZ,
  -- Ties a message to what caused it, so one status change cannot be texted
  -- twice if the gateway retries or two tabs both advance an order.
  dedupe_key   TEXT,
  priority     INT NOT NULL DEFAULT 5,
  order_id     UUID REFERENCES orders(id) ON DELETE SET NULL,
  CONSTRAINT outbound_status_valid CHECK (status IN ('pending','claimed','sent','failed','skipped')),
  CONSTRAINT outbound_channel_valid CHECK (channel IN ('sms','webhook','email'))
);

CREATE UNIQUE INDEX IF NOT EXISTS outbound_dedupe_idx
  ON outbound_messages(dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS outbound_pending_idx
  ON outbound_messages(status, priority, created_at) WHERE status IN ('pending','claimed');

-- ── SMS: dormant now, live later ──
--
-- The site can launch with no gateway. While sms_enabled is false, messages are
-- RECORDED as skipped rather than queued — so connecting a phone weeks later
-- cannot flush a backlog of "din ordre er klar" for meals eaten in September.
-- One such text teaches a customer to ignore every message you ever send.
--
-- expires_at is the second line of defence: every message carries its own shelf
-- life, so nothing stale goes out even if the flag were wrong.
-- Manual pause. Opening hours cover the predictable case; this covers a rush
-- the kitchen cannot see the end of, a dead fryer, an illness. Without it the
-- only way to stop orders is to take the site down — which also hides the
-- address, the phone number and the menu.
ALTER TABLE settings ADD COLUMN IF NOT EXISTS ordering_paused BOOLEAN DEFAULT FALSE;
ALTER TABLE settings ADD COLUMN IF NOT EXISTS pause_message TEXT;

-- Login attempts. The previous limiter was in-memory, which on serverless means
