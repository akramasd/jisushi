  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS auth_attempts_recent_idx ON auth_attempts(at DESC);
CREATE INDEX IF NOT EXISTS auth_attempts_ip_idx     ON auth_attempts(ip, at DESC);
ALTER TABLE auth_attempts ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION recent_auth_failures(p_ip TEXT, p_minutes INT DEFAULT 15)
RETURNS TABLE (ip_failures BIGINT, global_failures BIGINT)
LANGUAGE sql SECURITY INVOKER SET search_path = public, pg_catalog AS $$
  SELECT COUNT(*) FILTER (WHERE ip = p_ip AND NOT ok),
         COUNT(*) FILTER (WHERE NOT ok)
    FROM auth_attempts
   WHERE at > NOW() - (p_minutes || ' minutes')::INTERVAL;
$$;
REVOKE EXECUTE ON FUNCTION public.recent_auth_failures(TEXT, INT) FROM anon, authenticated, public;

