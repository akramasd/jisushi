-- ---- Web Push subscriptions (kitchen iPad alerts) ----
CREATE TABLE IF NOT EXISTS push_subscriptions (
  endpoint TEXT PRIMARY KEY,
  keys JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Locked down: no anon policy. Subscriptions are registered through a server
-- route, and read only by the alert sender using the service-role key.
ALTER TABLE push_subscriptions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS anon_all_push_subscriptions ON push_subscriptions;
