  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  price NUMERIC(10,2) NOT NULL,
  category TEXT,
  image_url TEXT,
  is_available BOOLEAN DEFAULT TRUE
);

-- Backfill: add image_url to pre-existing databases (no-op if already present)
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS image_url TEXT;

-- Orders (dine-in vs takeaway)
CREATE TABLE IF NOT EXISTS orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  order_no INT GENERATED BY DEFAULT AS IDENTITY,
  customer_name TEXT,
  customer_phone TEXT,
  table_number INT,
  items JSONB NOT NULL,
  status TEXT DEFAULT 'pending',
  total_price NUMERIC(10,2),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pickup_minutes INT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ;

-- ============================================================
-- Takeaway reliability + lifecycle
--
-- A customer ordering from mobile data 15 minutes away is the normal case, not
-- the edge case. The columns below exist so that a dropped connection cannot
-- create a duplicate order, and so the customer can confirm the kitchen has
-- actually seen theirs without phoning to ask.
-- ============================================================

-- Dedupe key generated by the client, one per checkout attempt. If the response
-- is lost and the customer taps again, the retry carries the SAME key and the
-- unique index turns the second insert into a no-op instead of a second dinner.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS idempotency_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS orders_idempotency_idx
  ON orders(idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Unguessable handle for the customer's own status page. Not the order number:
-- order numbers are sequential, so /ordre/41 would let anyone read /ordre/42.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS public_token TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS orders_public_token_idx
  ON orders(public_token) WHERE public_token IS NOT NULL;

-- Lifecycle timestamps. Each state change is recorded rather than overwritten,
-- so "how long did we take last Friday" is answerable later.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS accepted_at    TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS ready_at       TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS cancelled_at   TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS cancel_reason  TEXT;
-- What the kitchen promised the customer, as a real time rather than "30 min".
ALTER TABLE orders ADD COLUMN IF NOT EXISTS ready_estimate TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS channel        TEXT DEFAULT 'takeaway';

-- Valid states. Applied only if every existing row already conforms, so
-- re-running this on a live database cannot fail halfway through.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'orders_status_valid')
     AND NOT EXISTS (
       SELECT 1 FROM orders
       WHERE status NOT IN ('pending','accepted','ready','completed','cancelled')
     )
  THEN
    ALTER TABLE orders ADD CONSTRAINT orders_status_valid
      CHECK (status IN ('pending','accepted','ready','completed','cancelled'));
  END IF;
END $$;

-- History is searched by phone and by order number, both on recent rows only.
CREATE INDEX IF NOT EXISTS orders_phone_idx  ON orders(customer_phone);
CREATE INDEX IF NOT EXISTS orders_no_idx     ON orders(order_no DESC);

