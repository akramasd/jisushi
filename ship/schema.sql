-- Enable Realtime for instant KDS + menu updates
-- `orders` is deliberately NOT in the realtime publication.
--
-- Realtime respects RLS, and anon has no policy on orders — but publishing a
-- table of phone numbers is a door worth not building at all. The kitchen
-- screen polls an authenticated route instead.
--
-- The DROP matters: an earlier version of this schema ADDed orders to the
-- publication, and re-running the file on an existing database would otherwise
-- leave that in place. Removing it is the whole point of re-running.
DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime DROP TABLE orders;
EXCEPTION WHEN OTHERS THEN NULL; END $$;
DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE menu_items;
EXCEPTION WHEN OTHERS THEN NULL; END $$;

-- ============================================================
-- RLS — least privilege
--
-- The anon key is PUBLIC. It ships inside the JavaScript bundle of every page,
-- so `USING (true)` is not a permission model: it means anyone who opens
-- devtools can read every customer's name and phone number, rewrite prices, or
-- delete tonight's orders — without ever loading the app's UI.
--
-- Rule applied below: anon may read the menu, and nothing else. Every write,
-- and every read of personal data, goes through a server route holding the
-- service-role key, which bypasses RLS by design.
-- ============================================================

ALTER TABLE menu_items        ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders            ENABLE ROW LEVEL SECURITY;
ALTER TABLE loyalty_customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE settings          ENABLE ROW LEVEL SECURITY;   -- was never enabled; holds webhook_secret

-- Remove the old permissive policies wherever they were applied.
DROP POLICY IF EXISTS anon_all ON menu_items;
DROP POLICY IF EXISTS anon_all ON orders;
DROP POLICY IF EXISTS anon_all ON loyalty_customers;
DROP POLICY IF EXISTS anon_all ON settings;

-- menu_items: public read. It is the menu — it is on the wall outside.
-- No public write: a writable price column is a 1 kr sushi box.
DROP POLICY IF EXISTS menu_public_read ON menu_items;
CREATE POLICY menu_public_read ON menu_items
  FOR SELECT TO anon, authenticated
  USING (true);

-- orders: no anon access at all, in either direction.
--   reads  -> /api/kitchen/orders (staff session + service role)
--   writes -> /api/checkout       (server-side repricing + service role)
-- No policy is created, so with RLS on, anon is denied by default.

-- loyalty_customers: personal data. Server-side only, same reasoning.

-- settings: holds webhook_secret. Server-side only. Never expose to a browser.

-- push_subscriptions: delivery endpoints are write-once from the client and
-- must not be enumerable — otherwise anyone can list, or hijack, staff alerts.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_tables WHERE tablename = 'push_subscriptions') THEN
    EXECUTE 'ALTER TABLE push_subscriptions ENABLE ROW LEVEL SECURITY';
    EXECUTE 'DROP POLICY IF EXISTS anon_all_push_subscriptions ON push_subscriptions';
  END IF;
END $$;

