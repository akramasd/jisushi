-- A message stuck in 'claimed' means the phone took it and never reported back.
-- Release it so the next poll picks it up; give up after five attempts rather
-- than retrying into the void.
CREATE OR REPLACE FUNCTION release_stale_claims(older_than_minutes INT DEFAULT 5)
RETURNS INT LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_catalog AS $$
DECLARE released INT;
BEGIN
  UPDATE outbound_messages SET status = 'pending', claimed_at = NULL
   WHERE status = 'claimed'
     AND claimed_at < NOW() - (older_than_minutes || ' minutes')::INTERVAL
     AND attempts < 5;
  GET DIAGNOSTICS released = ROW_COUNT;
  UPDATE outbound_messages SET status = 'failed' WHERE status = 'claimed' AND attempts >= 5;
  RETURN released;
END $$;

CREATE OR REPLACE FUNCTION purge_old_events(retain_days INT DEFAULT 30)
RETURNS INT LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_catalog AS $$
DECLARE removed INT;
BEGIN
  DELETE FROM system_events WHERE created_at < NOW() - (retain_days || ' days')::INTERVAL;
  GET DIAGNOSTICS removed = ROW_COUNT;
  RETURN removed;
END $$;

CREATE OR REPLACE FUNCTION purge_old_orders(retain_days INT DEFAULT 30)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE removed INT;
BEGIN
  DELETE FROM orders WHERE created_at < NOW() - (retain_days || ' days')::INTERVAL;
  GET DIAGNOSTICS removed = ROW_COUNT;
  RETURN removed;
END $$;

